`timescale 1ns/1ps

module mppt_core_tb;

    parameter width = 10;

    reg clk;
    reg rst;
    reg [width-1:0] V;
    reg [width-1:0] I;

    wire [1:0] Dc_out;

    //====================================================
    // Instância do DUT
    //====================================================

    mppt_core #(width) dut (
        .clk(clk),
        .rst(rst),
        .V(V),
        .I(I),
        .Dc_out(Dc_out)
    );

    //====================================================
    // Clock de 100 MHz (10 ns)
    //====================================================

    initial begin
        clk = 0;
        forever #5 clk = ~clk;
    end

    //====================================================
    // Monitor
    //====================================================

    initial begin
        $display("---------------------------------------------------------------");
        $display("Tempo\tState\tV\tI\tP\tDc_out");
        $display("---------------------------------------------------------------");

        $monitor("%0t\t%d\t%d\t%d\t%d\t%b",
                 $time,
                 dut.state,
                 V,
                 I,
                 dut.P_newer,
                 Dc_out);
    end

    //====================================================
    // Estímulos
    //====================================================

    initial begin

        rst = 1;
        V = 0;
        I = 0;

        #20;
        rst = 0;

        //------------------------------------------------
        // Caso 1
        // Potência aumenta
        //------------------------------------------------

        @(posedge clk);
        V = 100;
        I = 5;

        repeat(8) @(posedge clk);

        //------------------------------------------------
        // Caso 2
        // Potência aumenta novamente
        //------------------------------------------------

        V = 120;
        I = 5;

        repeat(8) @(posedge clk);

        //------------------------------------------------
        // Caso 3
        // Potência diminui
        //------------------------------------------------

        V = 110;
        I = 3;

        repeat(8) @(posedge clk);

        //------------------------------------------------
        // Caso 4
        // Potência aumenta mas tensão diminui
        //------------------------------------------------

        V = 90;
        I = 8;

        repeat(8) @(posedge clk);

        //------------------------------------------------
        // Caso 5
        // Potência igual (deve permanecer em IDLE)
        //------------------------------------------------

        V = 90;
        I = 8;

        repeat(8) @(posedge clk);

        //------------------------------------------------

        $display("Fim da simulacao.");
        $finish;

    end

endmodule